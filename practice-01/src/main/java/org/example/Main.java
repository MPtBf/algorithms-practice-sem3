package org.example;

/**
 * Быстрая сортировка (схема Хоара) — объект практического исследования practice-01:
 * экспериментально подтверждаем сложность O(N·log N) на типичных входах
 * и O(N²) на вырожденном входе (см. {@link WorstCaseBuilder}, {@link Benchmark}).
 *
 * <p>Идея: выбираем опорный элемент, «размазываем» меньшие влево, большие вправо
 * (партиционирование) и рекурсивно сортируем две половины. Каждый уровень рекурсии
 * обрабатывает весь массив => работа на уровень ~N; уровней ~log N при сбалансированных
 * разбиениях (итого O(N·log N)) и ~N при вырожденных (итого O(N²)).</p>
 */
public class Main {

    /**
     * Демонстрационная точка входа: сортирует небольшой массив и печатает его.
     * К самому эксперименту не относится — полезна только для быстрой ручной проверки.
     *
     * @param args не используется
     */
    public static void main(String[] args) {
        int[] numbers = {1, 2, 10, 1, 9, 7, 8};

        quickSort(numbers); // сортировка «на месте», возвращать ничего не нужно

        for (int number: numbers){
            System.out.print(number);
            System.out.print(" ");
        }
        System.out.println();
    }

    /**
     * Публичный вход в сортировку: сортирует весь массив целиком.
     * Отдельный метод нужен, чтобы рекурсивная версия не требовала вызывающего
     * самому вычислять границы left/right.
     *
     * @param a массив, сортируется in-place (без выделения памяти)
     */
    public static void quickSort(int[] a) {
        quickSort(a, 0, a.length - 1); // весь массив: от первого до последнего индекса
    }

    /**
     * Рекурсивное ядро: сортирует участок {@code a[left..right]} (включительно).
     *
     * <p>Партиционирование по Хоару отличается от «классической» схемы Темина тем, что
     * два указателя идут навстречу и обмениваются элементами, а после прохода границы
     * рекурсии берутся по позициям {@code j} и {@code i} (элемент, равный пивоту, может
     * оказаться с любой стороны — зато обе половины продвигаются).</p>
     *
     * @param a     сортируемый массив (in-place)
     * @param left  левая граница текущего участка
     * @param right правая граница текущего участка
     */
    private static void quickSort(int[] a, int left, int right) {
        if (left >= right) return; // базис рекурсии: пустой участок или один элемент — уже отсортированы

        // Опорный элемент — из СЕРЕДИНЫ участка: на отсортированном входе
        // это близко к медиане, поэтому sorted-сценарий остаётся O(N·log N), а не вырождается в O(N²).
        // Вычисление left + (right-left)/2 вместо (left+right)/2 — защита от переполнения int.
        int pivot = a[left + (right - left) / 2];
        int i = left;  // левый указатель: идёт вправо
        int j = right; // правый указатель: идёт влево
        while (i <= j) {
            // Двигаем i, пока элементы СТРОГО меньше пивота: остановка — на первом >= пивота
            while (a[i] < pivot) i++;
            // Двигаем j, пока элементы СТРОГО больше пивота: остановка — на первом <= пивота
            while (a[j] > pivot) j--;

            // Оба указателя остановились на элементах, которые «не на своём месте» — меняем их.
            // После обмена слева гарантированно <= пивота не позднее этой позиции, справа >= пивота.
            if (i <= j) {
                int temporary = a[i];
                a[i] = a[j];
                a[j] = temporary;
                i++; // оба указателя сдвигаются: обмененные элементы уже обработаны
                j--;
            }
        }

        // Рекурсия по двум необработанным кускам (участок a[j+1..i-1] уже на своём месте):
        // левая половина [left..j] и правая [i..right]; пустые пары отсекаются базисом выше.
        if (left < j) quickSort(a, left, j);
        if (i < right) quickSort(a, i, right);
    }
}
