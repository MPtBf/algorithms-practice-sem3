package org.example;

/**
 * Конструктор «худшего» входа для QuickSort из {@link Main}.
 *
 * <p>Возвращает перестановку чисел 0..N-1 так, что на каждом шаге партиционирования
 * опорный элемент (который quickSort берёт с середины окна) оказывается <b>минимумом
 * текущего окна</b>. Тогда левая половина разбиения пуста, правая — на элемент меньше,
 * глубина рекурсии вырастает до ~N вместо ~log N => суммарная работа O(N²)
 * (экспериментально: наклон ≈ 2.1, R² ≈ 0.999 для кривой N² в результатах practice-01).</p>
 *
 * <p>Почему окна — это суффиксы: при пивоте-минимуме разбиение даёт части размерами 0 и N-1,
 * поэтому следующий рекурсивный вызов обрабатывает ровно участок [k+1..N-1] исходного массива —
 * то есть окна на шагах k = 0, 1, 2, ... идут подряд: [0..N-1], [1..N-1], [2..N-1], ...</p>
 */
public class WorstCaseBuilder {

    /**
     * Строит вырожденную перестановку длины n.
     *
     * @param n размер массива (степень двойки в бенчмарке, но работает для любого n >= 0)
     * @return массив length==n, содержащий значения 0..n-1 в «худшем» для quickSort порядке
     */
    public static int[] build(int n) {
        // origin — рабочая копия 0..n-1, которую мы постепенно перемешиваем свопами:
        // после свопов origin хранит значения в позициях, которые quickSort будет читать на каждом шаге.
        int[] origin = new int[n];
        for (int i = 0; i < n; i++) {
            origin[i] = i;
        }

        // values — итоговый массив (перестановка): values[p] = k записывает «нужное» значение
        // в позицию p — ту, где quickSort на k-м шаге увидит середину окна.
        int[] values = new int[n];
        for (int k = 0; k < n; k++) {
            // m — середина окна [k..n-1] (тот же расчёт left + (right-left)/2, что в Main.quickSort).
            // Первый шаг k=0 — окно весь массив; дальше окна — суффиксы, см. Javadoc класса.
            int m = k + (n - 1 - k) / 2;
            int p = origin[m];      // значение, которое quickSort выберет пивотом на этом шаге
            values[p] = k;          // «спускаем» ему ранг k: в итоговом массиве оно станет
                                    // минимумом окна k => пивот = минимум => разбиение 0 : N-1-k
            // Перемешиваем origin: выталкиваем обменённое значение из середины влево,
            // чтобы на следующих итерациях середины окон брали оставшиеся неиспользованные значения.
            int tmp = origin[k];
            origin[k] = origin[m];
            origin[m] = tmp;
        }
        return values;
    }
}
